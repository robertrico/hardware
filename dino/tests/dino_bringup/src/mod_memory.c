/* Memory board: 32K program ROM + 32K RAM + their MDR buffers + the
   write/steering gates. Rig owns the whole address bus.

   Netlist-verified structure (memory.kicad_sch, 2026-07-23):
     U24 AT28C256  ROM: A0-14 = M0-14, ~CE = ROM_EN (=M15, selected LOW
               so the ROM answers 0x0000-0x7FFF), ~OE = ~{ROM_OUT},
               ~WE strapped +5V (write-protected in copper).
     U26 MCM60256AP RAM: A0-14 = M0-14, ~CE = ~{RAM_EN} (selected LOW =
               M15 high = 0x8000-0xFFFF), ~OE = ~{RAM_OUT},
               ~WE = ~{RAM_WRITE_EN}.
     U19 '245  ROM -> MDR, DIR strapped A->B, CE = ~{ROM_OUT}.
     U21 '245  RAM <-> MDR, DIR = ~{WRITE_DIR}, CE = ~{RAM_MDR_EN}.
     U51 '00   all four gates:
               ~{WRITE_DIR}    = INV(WRITE_DIR)
               ~{RAM_WRITE_EN} = NAND(WRITE_DIR, ~{CLK})  <- the write
                     WINDOW. The v0.0.2 '121 one-shot is GONE: the pulse
                     is a gate off the clock phase, nothing to tune.
               RAM_MDR_DIS     = NAND(~{RAM_OUT}, ~{WRITE_DIR})
               ~{RAM_MDR_EN}   = INV(RAM_MDR_DIS)
               i.e. U21 CE = AND(~{RAM_OUT}, ~{WRITE_DIR}) — SCHEMATIC
               BUG 2's fix in copper: the buffer opens for a RAM read or
               a RAM write, never merely because MAR parked on a RAM
               address. `memory.idle` is the test that retires it.

   Expected gate values come from mem_expect.h (host-tested model —
   hosttest/test_mem_expect.c); ROM contents from progrom_expect.h
   (generated by docs/notes/progrom_gen.py, host-tested).

   Two burns, auto-detected from byte 0:
     DIAG (PROG_diag.bin): content-addressed, SELF-NAMING on 0 and every
          2^k — a mis-decoded address line reports the address the chip
          actually saw. Burn FIRST: 15 address lines is the biggest
          one-hole surface on the machine.
     REAL (PROG.bin): the milestone program (adds two numbers).

   PIN LAYOUT (bench-driven, 2026-07-23): both byte buses ride ONE
   unbroken 24-pin run D53 -> D30 — MDR0-7 on D53-D46, M0-M15 on
   D45-D30, each ascending, a ribbon per bus with no controls
   interleaved. Signals follow on D29 -> D22 (U51 in chip pin order)
   plus the D19 spill. Consequence: neither bus is byte-aligned on an
   AVR port any more, so this module drives and samples BOTH PER PIN
   (m_drive/mdr_read/mdr_write below) instead of using the harness's
   fixed-port helpers. The address is static per access — settle()
   dominates, and the 32768-read romcrc sweep still lands well under a
   second.

   Bus discipline: the rig drives MDR only while no board buffer does
   (mem_mdr_driven); it never provokes a fight state (mem_fight).

   Rig-internal probes (in the bundle): ~{WRITE_DIR} (U51.3),
   ~{RAM_WRITE_EN} (U51.6), RAM_MDR_DIS (U51.8), ~{RAM_MDR_EN} (U51.11).

   Driven lines: M0 M1 M2 M3 M4 M5 M6 M7 M8 M9 M10 M11 M12 M13 M14
   M15=ROM_EN ~{RAM_EN} ~{RAM_OUT} ~{ROM_OUT} WRITE_DIR ~{CLK}
   (series R).
   Sampled lines: MDR0 MDR1 MDR2 MDR3 MDR4 MDR5 MDR6 MDR7 (bidir — the
   rig drives them during RAM writes, so series R on those too) + the
   four probes.
   (coverage: every contract signal named). */

static hwpin_t P_IN[MEI_COUNT], P_LOG[MEO_COUNT], P_MDR[8], P_M[16];
